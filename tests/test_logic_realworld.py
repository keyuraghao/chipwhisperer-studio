def cap_of(sig, sr, t0, t1, **kw):
    n = int((t1 - t0) * sr)
    return LogicCapture.from_edges(synth.render(sig, sr, t0, n, **kw), n, sr, 0)


def chans(cap):
    return {c.name: (c.init, c.edges.tolist()) for c in cap.channels}


