    r = D.decode(cap_of({"tck": tck, "tms": tms, "tdi": tdi, "tdo": tdo}, 10e6, 0, t + 1e-6), "jtag", {"tck": 0, "tms": 1, "tdi": 2, "tdo": 3}, {})
